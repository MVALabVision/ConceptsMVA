let current = 'en';
const listeners = new Set();

export function getLang() {
  return current;
}

export function detectLang() {
  try {
    const saved = localStorage.getItem('mva.lang');
    if (saved === 'en' || saved === 'vi') return saved;
  } catch { /* ignore */ }
  const nav = (typeof navigator !== 'undefined' && navigator.language) || '';
  return nav.toLowerCase().startsWith('vi') ? 'vi' : 'en';
}

export function setLang(lang) {
  current = lang === 'vi' ? 'vi' : 'en';
  try { localStorage.setItem('mva.lang', current); } catch { /* ignore */ }
  if (typeof document !== 'undefined') {
    document.documentElement.lang = current;
    applyI18n();
  }
  for (const fn of listeners) fn(current);
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key, vars = {}) {
  const table = STRINGS[current] || STRINGS.en;
  let s = table[key] ?? STRINGS.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

// Apply to static markup: data-i18n="key" (textContent), data-i18n-ph="key" (placeholder), etc.
export function applyI18n(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of root.querySelectorAll('[data-i18n-ph]')) node.setAttribute('placeholder', t(node.dataset.i18nPh));
  for (const node of root.querySelectorAll('[data-i18n-title]')) node.setAttribute('title', t(node.dataset.i18nTitle));
  for (const node of root.querySelectorAll('[data-i18n-aria]')) node.setAttribute('aria-label', t(node.dataset.i18nAria));
}

export { STRINGS };
